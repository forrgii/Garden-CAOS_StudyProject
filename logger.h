#ifndef LOGGER_H
#define LOGGER_H

// ============================================
//  Модуль логирования
//  Пишет одновременно в stdout и в лог-файл.
//  Каждый запуск создаёт новый файл вида:
//      logs/simulation_YYYY-MM-DD_HH-MM-SS.log
//  Файл открывается через системный вызов open(),
//  запись — через write().
// ============================================

// Инициализация: создаёт директорию logs/ (если её нет)
// и открывает новый лог-файл с timestamp в имени.
// dir — директория для логов (например, "logs").
// prefix — префикс имени (например, "simulation").
// Возвращает 0 при успехе, -1 при ошибке.
int  log_init(const char* dir, const char* prefix);

// Закрытие лог-файла.
void log_close(void);

// Форматированный вывод в stdout и в лог-файл.
void log_msg(const char* fmt, ...);

// Вывод только в лог-файл (без дублирования в stdout).
void log_file_only(const char* fmt, ...);

// Получить полный путь к текущему лог-файлу.
// Возвращает указатель на внутренний буфер или NULL.
const char* log_get_path(void);

#endif
